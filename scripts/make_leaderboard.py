"""
ConflictBench — Leaderboard generator
Reads every results/*/summary.json and writes results/leaderboard.md. The file
is generated: never edit it by hand. Runs on different data files (different
SHA-256) are never mixed in one table, because their scores are not comparable.

Usage: python scripts/make_leaderboard.py [--results-dir results] [--out results/leaderboard.md]
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.provenance import comparison_key


def load_summaries(results_dir: Path) -> List[dict]:
    out = []
    for path in sorted(Path(results_dir).glob("*/summary.json")):
        with path.open(encoding="utf-8") as f:
            data = json.load(f)
        data.setdefault("run_name", path.parent.name)
        out.append(data)
    return out


def _who(s: dict) -> str:
    if s.get("backend") == "strategy":
        return f"strategy: {s.get('strategy')}"
    label = s.get("model") or "?"
    if s.get("adapter"):
        label += f" + {s['adapter']}"
    return f"{s.get('backend', 'model')}: {label}"


def _fmt(x: Optional[float]) -> str:
    return "-" if x is None else f"{x:.3f}"


def render(summaries: List[dict]) -> str:
    groups: Dict[Tuple[str, str, str, str, str, str, str], List[dict]] = {}
    for s in summaries:
        groups.setdefault(comparison_key(s), []).append(s)

    lines = [
        "# ConflictBench leaderboard",
        "",
        "Generated by `scripts/make_leaderboard.py` from `results/*/summary.json`. Do not edit by hand.",
        "Score is the task-specific mean (single-step composite or multi-step reward) in [0, 1].",
        "The interval is a seeded 95% bootstrap CI over scenarios.",
        "Rankings separate dataset, task/version, scorer, protocol and selected scenarios.",
        "Historical rows without provenance remain in separate unversioned groups.",
        "",
    ]
    if not summaries:
        lines.append("No results yet.")
    # data sets ordered by most recent run first, for stable-but-useful output
    ordered = sorted(groups.items(), key=lambda kv: max(r.get("timestamp_utc", "") for r in kv[1]), reverse=True)
    for (sha, task, version, scorer, protocol, selection, scored), runs in ordered:
        first = runs[0]
        lines += [f"## Data set `{sha[:12]}`", "",
                  f"File: `{first.get('data_path', '?')}` | scenarios in file: {first.get('n_scenarios_in_data', '?')} "
                  f"| SHA-256: `{sha}`", "",
                  f"Task: `{task}` | version: `{version}` | scorer: `{scorer}`", "",
                  f"Protocol: `{protocol}` | selected scenarios: `{selection}`", "",
                  f"Scored scenarios: `{scored}`", "",
                  "| Rank | Run | Score | 95% CI | D1 | D2 | D3 | Parse fail | n | Skipped | Commit |",
                  "|---:|---|---:|---|---:|---:|---:|---:|---:|---:|---|"]
        runs = sorted(runs, key=lambda r: (-r["composite"]["mean"], r["run_name"]))
        for rank, r in enumerate(runs, 1):
            c = r["composite"]
            pd = r.get("per_difficulty", {})
            d = [pd.get(str(i), {}).get("mean") for i in (1, 2, 3)]
            commit = (r.get("git_commit") or "?")[:7] + ("*" if r.get("git_dirty") else "")
            lines.append(
                f"| {rank} | {_who(r)} (`{r['run_name']}`) | {c['mean']:.3f} | "
                f"{c['ci95_low']:.3f} - {c['ci95_high']:.3f} | {_fmt(d[0])} | {_fmt(d[1])} | {_fmt(d[2])} | "
                f"{r.get('parse_failure_rate', 0.0):.3f} | {r.get('n', '?')} | "
                f"{r.get('skipped_too_long', 0)} | {commit} |"
            )
        lines.append("")
    lines.append("`*` after a commit means the working tree had uncommitted changes when the run was made.")
    return "\n".join(lines) + "\n"


def main(argv=None) -> str:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--results-dir", default=str(ROOT / "results"))
    p.add_argument("--out", help="default: <results-dir>/leaderboard.md")
    args = p.parse_args(argv)
    results_dir = Path(args.results_dir)
    text = render(load_summaries(results_dir))
    out = Path(args.out) if args.out else results_dir / "leaderboard.md"
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out}", file=sys.stderr)
    return text


if __name__ == "__main__":
    main()
